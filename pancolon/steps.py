# Step 2 — convert tiles to HDF5 (DeepPATH)
# --------------------------------------------------------------------------

def step_to_hdf5(cfg, opts):
    deeppath = _tool(cfg, "deeppath")
    conv = os.path.join(deeppath, "DeepPATH_code", "00_preprocessing",
                        "0e_jpgtoHDF.py")
    tiles_dir = _work(cfg, "tiles")
    out_h5 = _hdf5_path(cfg)
    _mkdir(opts, os.path.dirname(out_h5))
    t = cfg.get("tile", {})
    # Step 1 tiles by physical pixel size (-P), and the tiler's <mag>.0/ output
    # folder is named after each slide's own *declared* objective power in its
    # header (20.0, 40.0, ...) -- which varies by scanner even though every
    # slide lands on the same target pixel size. When -P is used the tiler also
    # symlinks a stable str(pixel_size)/ folder (e.g. "0.504") alongside it, so
    # glob that instead of a magnification that can differ slide to slide. The
    # converter globs <slide>_files/str(--mag)/ (mode 1), so --mag MUST match
    # whichever folder name is actually on disk or it silently finds 0 images.
    mag = t["pixel_size"] if t.get("pixel_size") is not None \
        else cfg.get("magnification", "20x").rstrip("x")
    argv = [
        "python", conv,
        "--input_path", tiles_dir,
        "--output", out_h5,
        "--wSize", t.get("tile_size", 224),
        "--mag", mag,
        "--label", "he",
        "--subset", "complete",
    ]
    return run_stage(cfg, step="to_hdf5", env=_activation(cfg, TILING_ENV_KEY)[0], modules=_activation(cfg, TILING_ENV_KEY)[1], argv=argv,
                     dry_run=opts.dry_run, no_env_switch=opts.no_env_switch)


# --------------------------------------------------------------------------
# Step 3 — project tiles into the trained HPL encoder (BarlowTwins_3)
# --------------------------------------------------------------------------

def step_project(cfg, opts):
    hpl = _tool(cfg, "hpl")
    # Individual-file projection (projects one --real_hdf5), per HPL's
    # README_additional_cohort recipe — NOT the _dataset variant (train/val/test).
    proj = os.path.join(hpl, "run_representationspathology_projection.py")
    ckpt = require(cfg, "weights.hpl_checkpoint")
    model = cfg.get("weights", {}).get("hpl_model_name", "BarlowTwins_3")
    ds = cfg.get("dataset_name", "cohort")
    p = cfg.get("project", {})
    complete_h5 = _hdf5_path(cfg)
    # HPL's Data() reads datasets/<ds>/he/patches_hXXX_wXXX/hdf5_<ds>_he_train.h5
    # for the model init (num_samples). Our inference cohort only has a "complete"
    # set, so alias it as the train set (same tiles) so Data.training loads.
    if not opts.dry_run and os.path.exists(complete_h5):
        train_h5 = os.path.join(_hpl_patches_dir(cfg), f"hdf5_{ds}_he_train.h5")
        if not os.path.lexists(train_h5):
            os.symlink(os.path.basename(complete_h5), train_h5)
    _mkdir(opts, _work(cfg, "hpl"))
    argv = [
        "python", proj,
        "--checkpoint", ckpt,
        "--dataset", ds,
        "--marker", "he",
        "--real_hdf5", complete_h5,
        "--model", model,
        "--img_size", p.get("img_size", 224),
        "--z_dim", p.get("z_dim", 128),
        "--batch_size", p.get("batch_size", 64),
        "--main_path", _work(cfg, "hpl"),
        "--dbs_path", _work(cfg, "hdf5"),
    ]
    return run_stage(cfg, step="project", env=_activation(cfg, TILING_ENV_KEY)[0], modules=_activation(cfg, TILING_ENV_KEY)[1], argv=argv,
                     cwd=hpl, dry_run=opts.dry_run, no_env_switch=opts.no_env_switch)


