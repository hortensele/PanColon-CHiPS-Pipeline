# Step 8 — per-tile attention + CHiPS-annotated overlays
# --------------------------------------------------------------------------

def step_attention_map(cfg, opts):
    survclam = _tool(cfg, "survclam")
    script = os.path.join(survclam, "extract_last_layer_and_attention.py")
    inf = cfg.get("infer", {})
    b = cfg.get("build_pt", {})
    a = cfg.get("attention", {})
    results_dir = _results_dir(cfg)
    feature_dir = _work(cfg, "datasets", cfg.get("dataset_name", "cohort"),
                        b.get("model_key", "HPL_PANCOLON_20x"), "pt_files")
    tile_locs_dir = _work(cfg, "datasets", cfg.get("dataset_name", "cohort"),
                         b.get("model_key", "HPL_PANCOLON_20x"), "tile_ids")
    out_dir = _mkdir(opts, _work(cfg, "attention"))
    clinical = _clinical_or_manifest(cfg)
    # One representative fold's checkpoint drives the attention weights; the
    # CHiPS score annotated on each slide comes from step 7's aggregate.
    fold = 0 if inf.get("chips_folds", "all") == "all" else \
        int(str(inf["chips_folds"]).split(",")[0])
    split_csv = _external_split_csv(cfg)
    argv = [
        "python", script,
        "--results_dir", results_dir,
        "--split_csv", split_csv,
        "--dataset_name", cfg.get("dataset_name", "cohort"),
        "--clinical_csv", clinical,
        "--feature_dir", feature_dir,
        "--task_type", inf.get("task_type", "survival"),
        "--time_col", inf.get("time_col", "dfs_event_data"),
        "--event_col", inf.get("event_col", "dfs_event_ind"),
        "--bag_level", inf.get("bag_level", "patient"),
        "--fold", fold,
        "--tile_locs_dir", tile_locs_dir,
        "--out_dir", out_dir,
        "--which_sets", a.get("which_sets", "test"),
        "--skip_missing_slide_pt",
    ]
    return run_stage(cfg, step="attention_map", env=_activation(cfg, SURVCLAM_ENV_KEY)[0], modules=_activation(cfg, SURVCLAM_ENV_KEY)[1],
                     argv=argv, cwd=survclam,
                     dry_run=opts.dry_run, no_env_switch=opts.no_env_switch)


