# Step 7 — apply the trained CHiPS fold checkpoints (external inference)
# --------------------------------------------------------------------------

def step_infer_survival(cfg, opts):
    survclam = _tool(cfg, "survclam")
    script = os.path.join(survclam, "eval.py")
    inf = cfg.get("infer", {})
    b = cfg.get("build_pt", {})
    feature_dir = _work(cfg, "datasets", cfg.get("dataset_name", "cohort"),
                        b.get("model_key", "HPL_PANCOLON_20x"), "pt_files")
    save_dir = _mkdir(opts, _work(cfg, "survclam"))
    clinical = _clinical_or_manifest(cfg)
    # --split all => score every slide against every fold (external inference,
    # no split CSVs needed). Checkpoints are found via runs_root/dataset/run_sig.
    argv = [
        "python", script,
        "--dataset_name", inf.get("runs_root_dataset", "colon_united"),
        "--clinical_csv", clinical,
        "--runs_root", require(cfg, "weights.survclam_runs_root"),
        "--exp_code", inf.get("exp_code"),
        "--seed", inf.get("seed", 1),
        "--task_type", inf.get("task_type", "survival"),
        "--time_col", inf.get("time_col", "dfs_event_data"),
        "--event_col", inf.get("event_col", "dfs_event_ind"),
        "--bag_level", inf.get("bag_level", "patient"),
        "--pt_id_col", inf.get("pt_id_col", "slide_id"),
        "--feature_dir", feature_dir,
        "--embed_dim", b.get("embed_dim", 128),
        "--model_size", inf.get("model_size", "big"),
        "--fold", -1,
        "--split", "all",
        "--k", inf.get("k", 16),
    ]
    if inf.get("covariate_cols"):
        argv += ["--covariate_cols", inf["covariate_cols"],
                 "--cov_fusion", inf.get("cov_fusion", "concat")]
    extra = {"CHIPS_SAVE_DIR": save_dir}
    rc = run_stage(cfg, step="infer_survival", env=_activation(cfg, SURVCLAM_ENV_KEY)[0], modules=_activation(cfg, SURVCLAM_ENV_KEY)[1],
                   argv=argv, cwd=survclam, extra_env=extra,
                   dry_run=opts.dry_run, no_env_switch=opts.no_env_switch)
    if not opts.dry_run:
        from . import chips
        chips.aggregate_folds(cfg, save_dir)
    return rc


